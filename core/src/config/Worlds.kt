package cat.freya.khs.config

import cat.freya.alloy.annotation.*
import cat.freya.khs.KhsTypes

data class WorldConfig(
    var type: String, // dimension type
    var isFlat: Boolean = false,
) {
    fun migrate() {
        when (type) {
            // migrate bukkit types
            "FLAT" -> {
                type = "NORMAL"
                isFlat = true
            }
            "END" -> {
                type = "THE_END"
            }
            else -> {}
        }
    }

    companion object {
        fun default(types: KhsTypes) = WorldConfig(types.defaultDimensionType)
    }
}

data class KhsWorldsConfig(
    @Comment("DO NOT EDIT THIS FILE - It is autogenerated")
    @Comment("Please use /hs world ... commands instead")
    var worlds: MutableMap<String, WorldConfig> = mutableMapOf()
) {
    fun update(name: String, types: KhsTypes, fn: WorldConfig.() -> Unit) {
        val config = worlds[name] ?: WorldConfig.default(types)
        fn(config)
        worlds[name] = config
    }

    fun migrate() {
        worlds.forEach { it.value.migrate() }
    }
}
